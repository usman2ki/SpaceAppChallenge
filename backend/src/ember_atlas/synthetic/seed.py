"""Load the synthetic demo world through the *normal* import pipeline."""

from __future__ import annotations

import hashlib
from pathlib import Path

from ..ingest.covariates import import_coverage, import_landcover
from ..ingest.importer import import_bytes
from ..ingest.normalize import Declaration
from ..store.base import Store
from .generator import PRODUCT_OF, SyntheticSpec, SyntheticWorld, firms_csv_by_product, generate

SYNTHETIC_NOTE = "SYNTHETIC demo data generated by ember_atlas.synthetic - not NASA measurements"


def seed_demo(store: Store, out_dir: Path | None = None, spec: SyntheticSpec | None = None, with_coverage: bool = True) -> dict:
    spec = spec or SyntheticSpec()
    world = generate(spec)
    csvs = firms_csv_by_product(world)
    reports = []
    for product, data in csvs.items():
        name = f"SYNTHETIC_{product}_{spec.start[:4]}-{spec.end[:4]}_seed{spec.seed}.csv"
        if out_dir:
            out_dir.mkdir(parents=True, exist_ok=True)
            (out_dir / name).write_bytes(data)
        plats = [p for p, prod in PRODUCT_OF.items() if prod == product]
        start = min(spec.windows[p][0] for p in plats)
        end = max(spec.windows[p][1] for p in plats)
        rep = import_bytes(
            store,
            data,
            name,
            Declaration(
                data_origin="synthetic",
                source_id=product,
                source_url="synthetic://ember_atlas.synthetic.generator",
                period_start=start,
                period_end=end,
                query_bbox=list(spec.bbox),
                notes=SYNTHETIC_NOTE,
                platform_periods={p: spec.windows[p] for p in plats},
            ),
        )
        reports.append(rep)
    cov = lc = None
    if with_coverage:
        cov = import_coverage(
            store,
            world.coverage,
            name=f"SYNTHETIC coverage seed{spec.seed}",
            data_origin="synthetic",
            grid_size_km=spec.coverage_km,
            description="Synthetic valid-observation looks (clouds, MODIS swath gaps, a Terra outage). " + SYNTHETIC_NOTE,
        )
        lc = import_landcover(
            store,
            world.cells[["cell_id", "lc"]].rename(columns={"lc": "lc_class"}),
            name=f"SYNTHETIC land cover seed{spec.seed}",
            data_origin="synthetic",
            grid_size_km=spec.latent_km,
            description=SYNTHETIC_NOTE,
        )
    digest = hashlib.sha256(b"".join(csvs[k] for k in sorted(csvs))).hexdigest()
    return {"imports": reports, "coverage": cov, "landcover": lc, "fixture_sha256": digest, "world": world}


def describe_world(world: SyntheticWorld) -> dict:
    s = world.spec
    return {
        "seed": s.seed,
        "bbox": s.bbox,
        "period": [s.start, s.end],
        "platform_windows": s.windows,
        "true_log_ratio_vs_aqua": s.base_log_ratio,
        "seasonal_ratio_amplitude": s.seasonal_ratio_amp,
        "landcover_ratio_shift_viirs": s.lc_ratio_shift,
        "injected_excess_episode": s.excess_episode,
        "injected_deficit_episode": s.deficit_episode,
        "terra_outage": s.terra_outage,
        "static_source": s.static_source,
        "detections_by_platform": {p: int(c.sum()) for p, c in world.counts.items()},
    }
